func (h *Handlers) TestDB(w http.ResponseWriter, r *http.Request) {
	data, count, err := h.DB.From("jobs").Select("*", "exact", false).Execute()
	if err != nil {
		writeError(w, http.StatusInternalServerError, "DB query failed: "+err.Error())
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{
		"count": count,
		"data":  json.RawMessage(data),
	})
}
